-- 3.1 Stok per barang (termasuk barang tanpa transaksi)
WITH stok AS (
 SELECT b."KODE_BARANG", b."NAMA_BARANG", b."SATUAN", b."KATEGORI",
 COALESCE(SUM(d."QTY") FILTER (WHERE h."JENIS_TRANSAKSI" = 'MASUK'), 0) AS "TRANS_MASUK",
 COALESCE(SUM(d."QTY") FILTER (WHERE h."JENIS_TRANSAKSI" = 'KELUAR'), 0) AS "TRANS_KELUAR"
 FROM "MSBARANG" b
 LEFT JOIN "TRMUTASIDT" d ON d."KODE_BARANG" = b."KODE_BARANG"
 LEFT JOIN "TRMUTASIHD" h ON h."NO_TRANSAKSI" = d."NO_TRANSAKSI"
  AND h."TANGGAL" BETWEEN DATE '2021-01-01' AND DATE '2021-02-28'
 GROUP BY b."KODE_BARANG", b."NAMA_BARANG", b."SATUAN", b."KATEGORI"
)
SELECT *, "TRANS_MASUK" - "TRANS_KELUAR" AS "STOK_AKHIR"
FROM stok ORDER BY "KATEGORI" DESC, "KODE_BARANG";

-- 3.2 Stok per kategori dan satuan
WITH stok AS (
 SELECT b."KODE_BARANG", b."NAMA_BARANG", b."SATUAN", b."KATEGORI",
 COALESCE(SUM(d."QTY") FILTER (WHERE h."JENIS_TRANSAKSI" = 'MASUK'), 0) AS "TRANS_MASUK",
 COALESCE(SUM(d."QTY") FILTER (WHERE h."JENIS_TRANSAKSI" = 'KELUAR'), 0) AS "TRANS_KELUAR"
 FROM "MSBARANG" b
 LEFT JOIN "TRMUTASIDT" d ON d."KODE_BARANG" = b."KODE_BARANG"
 LEFT JOIN "TRMUTASIHD" h ON h."NO_TRANSAKSI" = d."NO_TRANSAKSI"
  AND h."TANGGAL" BETWEEN DATE '2021-01-01' AND DATE '2021-02-28'
 GROUP BY b."KODE_BARANG", b."NAMA_BARANG", b."SATUAN", b."KATEGORI"
)
SELECT "KATEGORI", "SATUAN", SUM("TRANS_MASUK") AS "TRANS_MASUK",
 SUM("TRANS_KELUAR") AS "TRANS_KELUAR", SUM("TRANS_MASUK"-"TRANS_KELUAR") AS "STOK_AKHIR"
FROM stok GROUP BY "KATEGORI", "SATUAN" ORDER BY "KATEGORI" DESC, "SATUAN";

-- 3.3 Total pengeluaran tertinggi; tampilkan semua yang seri, abaikan nol
WITH stok AS (
 SELECT b."KODE_BARANG", b."NAMA_BARANG", b."SATUAN", b."KATEGORI",
 COALESCE(SUM(d."QTY") FILTER (WHERE h."JENIS_TRANSAKSI" = 'MASUK'), 0) AS "TRANS_MASUK",
 COALESCE(SUM(d."QTY") FILTER (WHERE h."JENIS_TRANSAKSI" = 'KELUAR'), 0) AS "TRANS_KELUAR"
 FROM "MSBARANG" b
 LEFT JOIN "TRMUTASIDT" d ON d."KODE_BARANG" = b."KODE_BARANG"
 LEFT JOIN "TRMUTASIHD" h ON h."NO_TRANSAKSI" = d."NO_TRANSAKSI"
  AND h."TANGGAL" BETWEEN DATE '2021-01-01' AND DATE '2021-02-28'
 GROUP BY b."KODE_BARANG", b."NAMA_BARANG", b."SATUAN", b."KATEGORI"
), peringkat AS (
 SELECT *, DENSE_RANK() OVER (PARTITION BY "KATEGORI", "SATUAN" ORDER BY "TRANS_KELUAR" DESC) AS r
 FROM stok WHERE "TRANS_KELUAR" > 0
)
SELECT "KATEGORI", "SATUAN", "KODE_BARANG", "NAMA_BARANG", "TRANS_KELUAR"
FROM peringkat WHERE r = 1 ORDER BY "KATEGORI" DESC, "SATUAN", "KODE_BARANG";
