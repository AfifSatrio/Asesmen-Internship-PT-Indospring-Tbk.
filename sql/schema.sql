-- Jalankan sekali pada database kosong. SQL ini sumber setup resmi, bukan db push.
BEGIN;
CREATE TABLE "MSBARANG" (
 "KODE_BARANG" varchar(5) PRIMARY KEY,
 "NAMA_BARANG" varchar(50) NOT NULL,
 "SATUAN" varchar(5) NOT NULL,
 "KATEGORI" varchar(10) NOT NULL CHECK ("KATEGORI" IN ('SUBMAT','RAWMAT'))
);
CREATE TABLE "TRMUTASIHD" (
 "NO_TRANSAKSI" varchar(5) PRIMARY KEY CHECK (length(trim("NO_TRANSAKSI")) > 0),
 "TANGGAL" date NOT NULL,
 "JENIS_TRANSAKSI" varchar(10) NOT NULL CHECK ("JENIS_TRANSAKSI" IN ('MASUK','KELUAR')),
 "KATEGORI" varchar(10) NOT NULL CHECK ("KATEGORI" IN ('SUBMAT','RAWMAT'))
);
CREATE INDEX "TRMUTASIHD_TANGGAL_idx" ON "TRMUTASIHD" ("TANGGAL");
CREATE TABLE "TRMUTASIDT" (
 "NO_TRANSAKSI" varchar(5) NOT NULL REFERENCES "TRMUTASIHD"("NO_TRANSAKSI") ON DELETE CASCADE ON UPDATE CASCADE,
 "KODE_BARANG" varchar(5) NOT NULL REFERENCES "MSBARANG"("KODE_BARANG") ON DELETE RESTRICT ON UPDATE CASCADE,
 "QTY" integer NOT NULL CHECK ("QTY" > 0),
 PRIMARY KEY ("NO_TRANSAKSI", "KODE_BARANG")
);
COMMIT;
